/**
 * Латинаар бичсэн монгол талбарын нэрийг кирилл рүү ойролцоогоор хөрвүүлнэ:
 * «khungulukhKhugatsaa» → «Хунгулух хугацаа». Толинд байхгүй үед л.
 */
export function latinKirill(talbar: string): string {
  const ugs = talbar
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_.]+/g, " ")
    .trim()
    .toLowerCase();
  const KHOS: [RegExp, string][] = [
    [/kh/g, "х"], [/ts/g, "ц"], [/ch/g, "ч"], [/sh/g, "ш"], [/zh/g, "ж"],
    [/ya/g, "я"], [/yo/g, "ё"], [/yu/g, "ю"], [/ye/g, "е"],
  ];
  const NEG: Record<string, string> = {
    a: "а", b: "б", c: "ц", d: "д", e: "э", f: "ф", g: "г", h: "х", i: "и",
    j: "ж", k: "к", l: "л", m: "м", n: "н", o: "о", p: "п", q: "к", r: "р",
    s: "с", t: "т", u: "у", v: "в", w: "в", x: "кс", y: "й", z: "з",
  };
  let s = ugs;
  KHOS.forEach(([re, k]) => (s = s.replace(re, k)));
  s = s.replace(/[a-z]/g, (c) => NEG[c] || c);
  return s.charAt(0).toUpperCase() + s.slice(1);
}
